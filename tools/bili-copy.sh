put() { printf '%s' "$2" | pbcopy; echo "✅ 已复制到剪贴板：$1（${#2} 字）"; }

case "${1:-步骤}" in
  私信) put "给作者的私信" "$DM" ;;
  评论) put "评论区留言（长版）" "$COMMENT_LONG" ;;
  短评) put "评论区留言（短版）" "$COMMENT_SHORT" ;;
  动态) put "B 站动态" "$POST" ;;
  步骤|*)
    cat <<'STEPS'
════════════════════════════════════════════════════════════
 B 站发布：3 步（顺序很重要）
════════════════════════════════════════════════════════════

【1】先私信氵六青老师报备（比直接评论舒服得多）
       bash tools/bili-copy.sh 私信

【2】等他回、或者过一天没回也可以发评论 —— 在他视频/动态的评论区：
       bash tools/bili-copy.sh 评论      # 长版（推荐，讲清她特殊在哪）
       bash tools/bili-copy.sh 短评      # 想低调就用这版

【3】发你自己的 B 站动态（正文 + 两张图）
       bash tools/bili-copy.sh 动态
     图1：dist/xhs-post/1-封面-平常状态.png
     图2：dist/xhs-post/6-桌面版实拍.png（自己截一张，Cmd+Shift+4）

⚠️ 注意
   · B 站评论**不能带图**，所以评论是纯文字；图和链接放在你的动态里
   · 评论里放仓库地址一般没事，但别刷同样的评论（只发一条）
   · 老师若有任何保留意见 → 优先照办，改不动就撤下

发布助手：bash tools/bili-copy.sh 私信|评论|短评|动态
════════════════════════════════════════════════════════════
STEPS
    ;;
esac
